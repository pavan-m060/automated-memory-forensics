class PDFReportGenerator:
    """Creates a professional, case-specific forensic PDF report."""

    PDF_NAME = "forensic_report.pdf"

    def __init__(self) -> None:
        self.styles = self._build_styles()

    @staticmethod
    def _build_styles() -> dict[str, ParagraphStyle]:
        base = getSampleStyleSheet()

        return {
            "title": ParagraphStyle(
                "ForensicTitle",
                parent=base["Title"],
                fontName="Helvetica-Bold",
                fontSize=24,
                leading=30,
                alignment=TA_CENTER,
                spaceAfter=18,
            ),
            "subtitle": ParagraphStyle(
                "ForensicSubtitle",
                parent=base["Normal"],
                fontName="Helvetica",
                fontSize=11,
                leading=16,
                alignment=TA_CENTER,
                spaceAfter=8,
            ),
            "h1": ParagraphStyle(
                "ForensicH1",
                parent=base["Heading1"],
                fontName="Helvetica-Bold",
                fontSize=16,
                leading=20,
                spaceBefore=12,
                spaceAfter=8,
            ),
            "h2": ParagraphStyle(
                "ForensicH2",
                parent=base["Heading2"],
                fontName="Helvetica-Bold",
                fontSize=12,
                leading=16,
                spaceBefore=8,
                spaceAfter=5,
            ),
            "body": ParagraphStyle(
                "ForensicBody",
                parent=base["BodyText"],
                fontName="Helvetica",
                fontSize=9,
                leading=13,
                spaceAfter=6,
            ),
            "small": ParagraphStyle(
                "ForensicSmall",
                parent=base["BodyText"],
                fontName="Helvetica",
                fontSize=7.5,
                leading=10,
                spaceAfter=3,
            ),
            "label": ParagraphStyle(
                "ForensicLabel",
                parent=base["BodyText"],
                fontName="Helvetica-Bold",
                fontSize=8,
                leading=10,
            ),
            "warning": ParagraphStyle(
                "ForensicWarning",
                parent=base["BodyText"],
                fontName="Helvetica-Bold",
                fontSize=9,
                leading=13,
                spaceAfter=6,
            ),
            "finding": ParagraphStyle(
                "ForensicFinding",
                parent=base["BodyText"],
                fontName="Helvetica",
                fontSize=8,
                leading=11,
                spaceAfter=4,
            ),
        }

    @staticmethod
    def _safe(value: Any, default: str = "Not provided") -> str:
        if value is None:
            return default

        text = str(value).strip()

        if not text:
            return default

        return text

    @staticmethod
    def _format_list(value: Any) -> str:
        if isinstance(value, list):
            if not value:
                return "None"
            return ", ".join(str(item) for item in value)

        return PDFReportGenerator._safe(value, "None")

    @staticmethod
    def _page_header_footer(canvas, doc) -> None:
        canvas.saveState()

        width, height = A4

        canvas.setStrokeColor(colors.HexColor("#D0D5DB"))
        canvas.line(18 * mm, height - 16 * mm, width - 18 * mm, height - 16 * mm)

        canvas.setFont("Helvetica", 7)
        canvas.setFillColor(colors.HexColor("#4B5563"))
        canvas.drawString(
            18 * mm,
            height - 12 * mm,
            "DIGITAL FORENSICS — MEMORY ANALYSIS REPORT",
        )

        canvas.drawRightString(
            width - 18 * mm,
            height - 12 * mm,
            "CONFIDENTIAL",
        )

        canvas.line(18 * mm, 14 * mm, width - 18 * mm, 14 * mm)

        canvas.drawString(
            18 * mm,
            9 * mm,
            "Generated by Automated Rootkit / Process Injection Detector",
        )

        canvas.drawRightString(
            width - 18 * mm,
            9 * mm,
            f"Page {doc.page}",
        )

        canvas.restoreState()

    def generate(
        self,
        *,
        output_dir: str | Path,
        report: dict[str, Any],
    ) -> Path:
        output_path = Path(output_dir)
        output_path.mkdir(parents=True, exist_ok=True)

        pdf_path = output_path / self.PDF_NAME

        doc = BaseDocTemplate(
            str(pdf_path),
            pagesize=A4,
            rightMargin=18 * mm,
            leftMargin=18 * mm,
            topMargin=22 * mm,
            bottomMargin=20 * mm,
            title=self._safe(
                report.get("case_metadata", {}).get(
                    "report_title",
                    "Forensic Memory Analysis Report",
                )
            ),
            author=self._safe(
                report.get("case_metadata", {}).get(
                    "examiner_name",
                    "Automated Forensic Analysis System",
                )
            ),
            subject="Windows memory forensic analysis report",
        )

        frame = Frame(
            doc.leftMargin,
            doc.bottomMargin,
            doc.width,
            doc.height,
            id="normal",
        )

        doc.addPageTemplates(
            [
                PageTemplate(
                    id="forensic",
                    frames=frame,
                    onPage=self._page_header_footer,
                )
            ]
        )

        story = self._build_story(report)
        doc.build(story)

        return pdf_path

    def _build_story(self, report: dict[str, Any]) -> list[Any]:
        metadata = report.get("case_metadata", {})
        provenance = report.get("provenance", {})
        analysis = report.get("analysis", {})
        summaries = report.get("summaries", {})
        findings = report.get("correlated_findings", [])
        limitations = report.get("limitations", [])
        warnings = report.get("warnings", [])
        errors = report.get("errors", [])

        story: list[Any] = []

        # ---------------------------------------------------------
        # TITLE PAGE
        # ---------------------------------------------------------

        story.append(Spacer(1, 35 * mm))

        story.append(
            Paragraph(
                self._safe(
                    metadata.get(
                        "report_title",
                        "Forensic Memory Analysis Report",
                    )
                ),
                self.styles["title"],
            )
        )

        story.append(
            Paragraph(
                "Automated Windows Memory Forensics Examination",
                self.styles["subtitle"],
            )
        )

        story.append(Spacer(1, 15 * mm))

        title_data = [
            ["Case ID", self._safe(metadata.get("case_id"))],
            [
                "Examination ID",
                self._safe(metadata.get("examination_id")),
            ],
            [
                "Examiner",
                self._safe(metadata.get("examiner_name")),
            ],
            [
                "Organization",
                self._safe(metadata.get("organization")),
            ],
            [
                "Evidence ID",
                self._safe(metadata.get("evidence_id")),
            ],
            [
                "Evidence Description",
                self._safe(metadata.get("evidence_description")),
            ],
            [
                "Examination Date",
                self._safe(
                    analysis.get("analysis_time"),
                    datetime.now(timezone.utc).isoformat(),
                ),
            ],
        ]

        story.append(self._metadata_table(title_data))
        story.append(Spacer(1, 18 * mm))

        story.append(
            Paragraph(
                "This report contains automated forensic analysis results "
                "derived from the submitted memory image. Findings are "
                "analytical indicators and require qualified examiner review.",
                self.styles["warning"],
            )
        )

        story.append(PageBreak())

        # ---------------------------------------------------------
        # EXECUTIVE SUMMARY
        # ---------------------------------------------------------

        story.append(Paragraph("1. Executive Summary", self.styles["h1"]))

        conclusion = self._safe(
            report.get("conclusion"),
            "No conclusion was recorded.",
        )

        story.append(
            Paragraph(
                conclusion,
                self.styles["body"],
            )
        )

        story.append(
            Paragraph(
                "The examination applies multiple memory-forensics "
                "analysis modules and correlates their results. "
                "A finding should be interpreted in the context of the "
                "underlying evidence, analyzer limitations, and available "
                "Volatility plugins.",
                self.styles["body"],
            )
        )

        # ---------------------------------------------------------
        # CASE INFORMATION
        # ---------------------------------------------------------

        story.append(Paragraph("2. Case Information", self.styles["h1"]))

        case_description = self._safe(
            metadata.get("case_description"),
            "No investigation description was provided.",
        )

        story.append(
            Paragraph(
                case_description,
                self.styles["body"],
            )
        )

        story.append(
            self._metadata_table(
                [
                    ["Case ID", self._safe(metadata.get("case_id"))],
                    [
                        "Examination ID",
                        self._safe(metadata.get("examination_id")),
                    ],
                    [
                        "Examiner",
                        self._safe(metadata.get("examiner_name")),
                    ],
                    [
                        "Organization",
                        self._safe(metadata.get("organization")),
                    ],
                ]
            )
        )

        # ---------------------------------------------------------
        # SCOPE / OBJECTIVE
        # ---------------------------------------------------------

        story.append(Paragraph("3. Scope and Objective", self.styles["h1"]))

        story.append(
            Paragraph(
                "The objective of this examination is to identify and "
                "document indicators associated with hidden processes, "
                "suspicious process memory, anomalous modules, and "
                "hook-related artifacts within the supplied Windows "
                "memory image.",
                self.styles["body"],
            )
        )

        story.append(
            Paragraph(
                "The analysis is intended to support forensic triage "
                "and analyst investigation. Automated scores are not "
                "statistical probabilities of malware or compromise.",
                self.styles["body"],
            )
        )

        # ---------------------------------------------------------
        # EVIDENCE IDENTIFICATION
        # ---------------------------------------------------------

        story.append(Paragraph("4. Evidence Identification", self.styles["h1"]))

        evidence_rows = [
            ["Evidence ID", self._safe(metadata.get("evidence_id"))],
            [
                "Evidence Description",
                self._safe(metadata.get("evidence_description")),
            ],
            [
                "Memory Image",
                self._safe(
                    provenance.get("filename")
                    or provenance.get("memory_image")
                ),
            ],
            [
                "Size",
                self._safe(provenance.get("size_bytes")),
            ],
            [
                "SHA-256",
                self._safe(provenance.get("sha256")),
            ],
        ]

        story.append(self._metadata_table(evidence_rows))

        # ---------------------------------------------------------
        # METHODOLOGY
        # ---------------------------------------------------------

        story.append(Paragraph("5. Methodology", self.styles["h1"]))

        methodology = [
            "Validate and preserve the submitted memory image.",
            "Collect process views using Volatility process enumeration.",
            "Compare process views for psscan-only candidates.",
            "Analyze suspicious process memory and corroborating mappings.",
            "Analyze loaded DLL/module characteristics.",
            "Collect callback, SSDT, ETW and related hook indicators where available.",
            "Correlate analyzer findings at the process and artifact level.",
            "Assign explainable triage risk and confidence classifications.",
            "Generate structured JSON, HTML and PDF reporting artifacts.",
        ]

        for item in methodology:
            story.append(
                Paragraph(
                    f"• {item}",
                    self.styles["body"],
                )
            )

        # ---------------------------------------------------------
        # EXAMINATION ENVIRONMENT
        # ---------------------------------------------------------

        story.append(Paragraph("6. Examination Environment", self.styles["h1"]))

        environment_rows = [
            [
                "Python Version",
                self._safe(provenance.get("python_version")),
            ],
            [
                "Volatility Version",
                self._safe(provenance.get("volatility_version")),
            ],
            [
                "Analysis Time",
                self._safe(analysis.get("analysis_time")),
            ],
            [
                "Analysis Status",
                self._safe(analysis.get("status")),
            ],
            [
                "Real Forensic Analysis",
                self._safe(
                    analysis.get("is_real_forensic_analysis")
                ),
            ],
            [
                "Enabled Analyzers",
                self._format_list(
                    provenance.get("enabled_analyzers")
                ),
            ],
            [
                "Disabled Analyzers",
                self._format_list(
                    provenance.get("disabled_analyzers")
                ),
            ],
        ]

        story.append(self._metadata_table(environment_rows))

        # ---------------------------------------------------------
        # FINDINGS SUMMARY
        # ---------------------------------------------------------

        story.append(Paragraph("7. Findings Summary", self.styles["h1"]))

        summary_rows = [
            ["Analyzer", "Result"],
        ]

        for name, summary in summaries.items():
            if not isinstance(summary, dict):
                summary_rows.append([str(name), self._safe(summary)])
                continue

            result = []

            for key in (
                "total_processes",
                "process_count",
                "pslist_count",
                "psscan_count",
                "potential_hidden_count",
                "suspicious_regions",
                "potential_injection_findings",
                "total_modules",
                "suspicious_modules",
                "hook_related_findings",
                "records_analyzed",
            ):
                if key in summary:
                    result.append(f"{key}: {summary[key]}")

            summary_rows.append(
                [
                    str(name),
                    "; ".join(result) if result else "See detailed report",
                ]
            )

        story.append(self._data_table(summary_rows))

        # ---------------------------------------------------------
        # DETAILED FINDINGS
        # ---------------------------------------------------------

        story.append(PageBreak())
        story.append(Paragraph("8. Detailed Findings", self.styles["h1"]))

        if not isinstance(findings, list) or not findings:
            story.append(
                Paragraph(
                    "No correlated findings were recorded.",
                    self.styles["body"],
                )
            )
        else:
            for index, finding in enumerate(findings, start=1):
                if not isinstance(finding, dict):
                    continue

                story.extend(
                    self._finding_section(
                        index,
                        finding,
                    )
                )

        # ---------------------------------------------------------
        # CORRELATION AND RISK
        # ---------------------------------------------------------

        story.append(Paragraph("9. Correlation and Risk Assessment", self.styles["h1"]))

        correlation = report.get("correlation", {})
        correlation_summary = (
            correlation.get("summary", {})
            if isinstance(correlation, dict)
            else {}
        )

        correlation_rows = [
            [
                "Correlated Findings",
                self._safe(
                    correlation_summary.get(
                        "correlated_findings",
                        len(findings)
                        if isinstance(findings, list)
                        else 0,
                    )
                ),
            ],
            [
                "Correlation Basis",
                "Process-level association unless artifact-level "
                "corroboration is explicitly demonstrated.",
            ],
        ]

        story.append(self._metadata_table(correlation_rows))

        story.append(
            Paragraph(
                "Risk scores are triage scores used to prioritize "
                "analyst review. Confidence classifications describe "
                "the diversity of supporting evidence and must not be "
                "interpreted as statistical probabilities.",
                self.styles["body"],
            )
        )

        # ---------------------------------------------------------
        # LIMITATIONS
        # ---------------------------------------------------------

        story.append(Paragraph("10. Limitations", self.styles["h1"]))

        for limitation in limitations:
            story.append(
                Paragraph(
                    f"• {self._safe(limitation)}",
                    self.styles["body"],
                )
            )

        if warnings:
            story.append(Paragraph("Warnings", self.styles["h2"]))

            for warning in warnings:
                story.append(
                    Paragraph(
                        f"• {self._safe(warning)}",
                        self.styles["body"],
                    )
                )

        if errors:
            story.append(Paragraph("Errors", self.styles["h2"]))

            for error in errors:
                story.append(
                    Paragraph(
                        f"• {self._safe(error)}",
                        self.styles["body"],
                    )
                )

        # ---------------------------------------------------------
        # CONCLUSION
        # ---------------------------------------------------------

        story.append(Paragraph("11. Conclusion", self.styles["h1"]))

        story.append(
            Paragraph(
                conclusion,
                self.styles["body"],
            )
        )

        story.append(
            Paragraph(
                "The automated result should be considered an "
                "investigative aid. Final incident determinations "
                "should be made by a qualified examiner after review "
                "of the underlying memory evidence and relevant "
                "context.",
                self.styles["body"],
            )
        )

        # ---------------------------------------------------------
        # EXAMINER / REPORT INFORMATION
        # ---------------------------------------------------------

        story.append(Paragraph("12. Examiner and Report Information", self.styles["h1"]))

        story.append(
            self._metadata_table(
                [
                    [
                        "Examiner",
                        self._safe(metadata.get("examiner_name")),
                    ],
                    [
                        "Organization",
                        self._safe(metadata.get("organization")),
                    ],
                    [
                        "Case ID",
                        self._safe(metadata.get("case_id")),
                    ],
                    [
                        "Examination ID",
                        self._safe(metadata.get("examination_id")),
                    ],
                    [
                        "Generated",
                        datetime.now(timezone.utc).isoformat(),
                    ],
                ]
            )
        )

        # ---------------------------------------------------------
        # APPENDIX
        # ---------------------------------------------------------

        story.append(PageBreak())
        story.append(Paragraph("Appendix A — Evidence and Analysis Notes", self.styles["h1"]))

        story.append(
            Paragraph(
                "The JSON report generated alongside this PDF contains "
                "the structured analyzer output and should be retained "
                "with the PDF as the machine-readable examination record.",
                self.styles["body"],
            )
        )

        story.append(
            Paragraph(
                "The HTML report provides an investigator-oriented "
                "interactive representation of the same final report.",
                self.styles["body"],
            )
        )

        story.append(
            Paragraph(
                "This report does not by itself establish legal "
                "admissibility. Admissibility, evidentiary weight, "
                "chain-of-custody requirements, and examiner "
                "qualifications depend on the applicable jurisdiction "
                "and examination procedures.",
                self.styles["warning"],
            )
        )

        return story

    def _finding_section(
        self,
        number: int,
        finding: dict[str, Any],
    ) -> list[Any]:
        story: list[Any] = []

        case_id = self._safe(
            finding.get("finding_id"),
            f"CORR-{number:04d}",
        )

        pid = self._safe(finding.get("pid"), "N/A")
        process = self._safe(
            finding.get("process_name"),
            "Unknown process",
        )
        severity = self._safe(
            finding.get("severity"),
            "UNSPECIFIED",
        )
        confidence = self._safe(
            finding.get("confidence"),
            "UNSPECIFIED",
        )
        risk = self._safe(
            finding.get("risk_score"),
            "N/A",
        )

        story.append(
            Paragraph(
                f"Finding {number}: {case_id}",
                self.styles["h2"],
            )
        )

        metadata = [
            ["Process", process],
            ["PID", pid],
            ["Severity", severity],
            ["Confidence", confidence],
            ["Risk Score", f"{risk}/100" if risk != "N/A" else risk],
            [
                "Correlation Basis",
                self._safe(
                    finding.get(
                        "correlation_basis",
                        "Not specified",
                    )
                ),
            ],
        ]

        story.append(self._metadata_table(metadata))

        explanation = finding.get("explanation")

        if explanation:
            story.append(
                Paragraph(
                    f"<b>Analyst Lead:</b> {self._safe(explanation)}",
                    self.styles["finding"],
                )
            )

        indicators = finding.get("supporting_indicators", [])

        if isinstance(indicators, list) and indicators:
            story.append(
                Paragraph(
                    "Supporting Indicator Evidence",
                    self.styles["h2"],
                )
            )

            for indicator in indicators:
                if not isinstance(indicator, dict):
                    continue

                indicator_type = self._safe(
                    indicator.get("type"),
                    "Unknown indicator",
                )
                description = self._safe(
                    indicator.get("description"),
                    "No description",
                )
                source = self._safe(
                    indicator.get("source"),
                    "Unknown source",
                )

                story.append(
                    KeepTogether(
                        [
                            Paragraph(
                                f"<b>{indicator_type}</b> "
                                f"(source: {source})",
                                self.styles["finding"],
                            ),
                            Paragraph(
                                description,
                                self.styles["finding"],
                            ),
                        ]
                    )
                )

                evidence = indicator.get("evidence")

                if isinstance(evidence, dict) and evidence:
                    evidence_rows = [["Evidence", "Value"]]

                    for key, value in evidence.items():
                        if value in (None, "", {}):
                            continue

                        evidence_rows.append(
                            [
                                self._safe(key),
                                self._safe(value),
                            ]
                        )

                    if len(evidence_rows) > 1:
                        story.append(
                            self._data_table(evidence_rows)
                        )

        story.append(Spacer(1, 5 * mm))

        return story

    def _metadata_table(
        self,
        rows: list[list[str]],
    ) -> Table:
        data = []

        for label, value in rows:
            data.append(
                [
                    Paragraph(
                        self._safe(label),
                        self.styles["label"],
                    ),
                    Paragraph(
                        self._safe(value),
                        self.styles["small"],
                    ),
                ]
            )

        table = Table(
            data,
            colWidths=[45 * mm, 125 * mm],
            repeatRows=0,
        )

        table.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#F3F4F6")),
                    ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#D1D5DB")),
                    ("INNERGRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#E5E7EB")),
                    ("VALIGN", (0, 0), (-1, -1), "TOP"),
                    ("LEFTPADDING", (0, 0), (-1, -1), 6),
                    ("RIGHTPADDING", (0, 0), (-1, -1), 6),
                    ("TOPPADDING", (0, 0), (-1, -1), 5),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                ]
            )
        )

        return table

    def _data_table(
        self,
        rows: list[list[str]],
    ) -> Table:
        converted = []

        for row_index, row in enumerate(rows):
            converted.append(
                [
                    Paragraph(
                        self._safe(cell),
                        self.styles["label"]
                        if row_index == 0
                        else self.styles["small"],
                    )
                    for cell in row
                ]
            )

        if not converted:
            return Table([["No data"]])

        table = Table(
            converted,
            colWidths=[45 * mm, 125 * mm],
            repeatRows=1 if len(converted) > 1 else 0,
        )

        table.setStyle(
            TableStyle(
                [
                    (
                        "BACKGROUND",
                        (0, 0),
                        (-1, 0),
                        colors.HexColor("#E5E7EB"),
                    ),
                    (
                        "BOX",
                        (0, 0),
                        (-1, -1),
                        0.5,
                        colors.HexColor("#9CA3AF"),
                    ),
                    (
                        "INNERGRID",
                        (0, 0),
                        (-1, -1),
                        0.25,
                        colors.HexColor("#D1D5DB"),
                    ),
                    ("VALIGN", (0, 0), (-1, -1), "TOP"),
                    ("LEFTPADDING", (0, 0), (-1, -1), 5),
                    ("RIGHTPADDING", (0, 0), (-1, -1), 5),
                    ("TOPPADDING", (0, 0), (-1, -1), 4),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                ]
            )
        )

        return table